"""Write web/models.js from src/ge100pro/models.json (the page can't load JSON files when opened from disk)."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def render() -> str:
    data = json.loads((ROOT / "src" / "ge100pro" / "models.json").read_text(encoding="utf-8"))
    return ("// Generated by tools/gen_models_js.py from src/ge100pro/models.json -- do not edit by hand.\n"
            "window.GE100_MODELS = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")


if __name__ == "__main__":
    (ROOT / "web" / "models.js").write_text(render(), encoding="utf-8")
    print("wrote web/models.js")
